def get_exercises_by_group(muscle_group: str) -> List[Dict[str, Any]]:
    """Возвращает список упражнений для указанной группы мышц."""
    return [ex for ex in EXERCISES.values() if ex["muscle_group"] == muscle_group]


def get_exercise_by_id(exercise_id: str) -> Optional[Dict[str, Any]]:
    """Возвращает упражнение по ID."""
    return EXERCISES.get(exercise_id)


def get_workout_by_id(workout_id: str) -> Optional[Dict[str, Any]]:
    """Возвращает готовую тренировку по ID."""
    return READY_WORKOUTS.get(workout_id)


def get_tip_by_id(tip_id: str) -> Optional[Dict[str, Any]]:
    """Возвращает совет по ID."""
    return GENERAL_TIPS.get(tip_id)